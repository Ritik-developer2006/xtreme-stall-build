<script>
  // Fade-up animation on scroll
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('visible');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });
  
  document.querySelectorAll('.fade-up').forEach(el => observer.observe(el));

  // Parallax effect
  window.addEventListener('scroll', () => {
    const scrolled = window.scrollY;
    const heroBgLines = document.querySelector('.page-hero-bg-lines');
    if (heroBgLines) {
      heroBgLines.style.transform = `translateY(${scrolled * 0.5}px)`;
    }
  });

  // Lightbox Gallery Functionality
  const galleryImages = [
    { src: 'https://images.unsplash.com/photo-1552664730-d307ca884978?w=1200&auto=format&fit=crop&q=80', alt: 'Team Collaboration' },
    { src: 'https://images.unsplash.com/photo-1552999081-75d75c98868c?w=1200&auto=format&fit=crop&q=80', alt: 'Design Process' },
    { src: 'https://images.unsplash.com/photo-1552664730-1d73ca13cbf0?w=1200&auto=format&fit=crop&q=80', alt: 'Fabrication Work' },
    { src: 'https://images.unsplash.com/photo-1552664797-e95f7f2a3007?w=1200&auto=format&fit=crop&q=80', alt: 'Creative Design' },
    { src: 'https://images.unsplash.com/photo-1552664797-85f4b93e2ba1?w=1200&auto=format&fit=crop&q=80', alt: 'Exhibition Setup' },
    { src: 'https://images.unsplash.com/photo-1552664806-b06f4b6f90f8?w=1200&auto=format&fit=crop&q=80', alt: 'Final Showcase' }
  ];

  let currentImageIndex = 0;

  function openLightbox(index) {
    currentImageIndex = index;
    const lightbox = document.getElementById('lightbox');
    const lightboxImg = document.getElementById('lightbox-img');
    const lightboxAlt = document.getElementById('lightbox-alt');
    const lightboxCounter = document.getElementById('lightbox-counter');
    
    lightboxImg.src = galleryImages[index].src;
    lightboxImg.alt = galleryImages[index].alt;
    lightboxAlt.textContent = galleryImages[index].alt;
    lightboxCounter.textContent = (index + 1) + ' / ' + galleryImages.length;
    lightbox.classList.add('active');
    document.body.style.overflow = 'hidden';
  }

  function closeLightbox() {
    const lightbox = document.getElementById('lightbox');
    lightbox.classList.remove('active');
    document.body.style.overflow = 'auto';
  }

  function nextImage() {
    currentImageIndex = (currentImageIndex + 1) % galleryImages.length;
    openLightbox(currentImageIndex);
  }

  function prevImage() {
    currentImageIndex = (currentImageIndex - 1 + galleryImages.length) % galleryImages.length;
    openLightbox(currentImageIndex);
  }

  // Close lightbox on background click
  const lightboxEl = document.getElementById('lightbox');
  if (lightboxEl) {
    lightboxEl.addEventListener('click', function(e) {
      if (e.target === this) {
        closeLightbox();
      }
    });
  }

  // Keyboard navigation
  document.addEventListener('keydown', function(e) {
    const lightbox = document.getElementById('lightbox');
    if (lightbox && lightbox.classList.contains('active')) {
      if (e.key === 'ArrowRight') nextImage();
      if (e.key === 'ArrowLeft') prevImage();
      if (e.key === 'Escape') closeLightbox();
    }
  });
</script>

